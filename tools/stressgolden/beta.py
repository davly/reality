#!/usr/bin/env python3
"""Generate testdata/stress/precision_beta.json: the precision claims of
prob.BetaQuantile, prob.BetaQuantileComplement and prob.BetaQuantileXY.

The reference values are not recomputed here. They are read from
testdata/stress/beta_quantile.json, the 800-digit mpmath table written by
tools/stressgolden/beta_quantile.py, and rounded to the nearest float64 by
Python's correctly rounded float(); the inputs a, b and p are rounded the same
way, which is also how the Go test of that table reads them. The script needs
no mpmath and uses the standard library only.

Every row of the table yields three cases:
  - prob.BetaQuantile(a, b, p) against x;
  - prob.BetaQuantileXY.y, the second result of BetaQuantileXY(a, b, p),
    against 1 - x;
  - prob.BetaQuantileComplement(b, a, p), the shapes swapped, against 1 - x
    (1 - I_x(a, b) = p is I_{1-x}(b, a) = p, with p exact).
Each is held to the relative error its doc comment states for that row's
region: the core range (a, b in [0.5, 100], p in [1e-6, 0.999]) or the whole
table. The claims were measured against the full-precision table; the
float64 rounding of the reference adds at most 2^-53 to the error, which the
stated bounds already include.

This is a development-time generator, not an implementation: Go code never
imports it, and the library keeps zero dependencies. Run from the repository
root:

    python3 tools/stressgolden/beta.py
"""

import json
import os

SRC = os.path.join("testdata", "stress", "beta_quantile.json")
OUT = os.path.join("testdata", "stress", "precision_beta.json")
DOC = "prob/betaquantile.go"

# (func, region) -> (tol, the doc-comment wording it reads)
CLAIMS = {
    ("prob.BetaQuantile", True): (
        4e-15,
        "BetaQuantile: 'relative error at most 4e-15 for a, b in [0.5, 100] and p in [1e-6, 0.999]'",
    ),
    ("prob.BetaQuantile", False): (
        7e-14,
        "BetaQuantile: 'at most 7e-14 over the whole table'",
    ),
    ("prob.BetaQuantileXY.y", True): (
        3e-15,
        "BetaQuantileXY: 'y has relative error at most 3e-15 over the core range of BetaQuantile'",
    ),
    ("prob.BetaQuantileXY.y", False): (
        2.5e-13,
        "BetaQuantileXY: 'y has ... at most 2.5e-13 over the whole table'",
    ),
    ("prob.BetaQuantileComplement", True): (
        2.5e-13,
        "BetaQuantileComplement: 'Against the same table, read with the shapes swapped ... the relative error is at most 2.5e-13'",
    ),
    ("prob.BetaQuantileComplement", False): (
        2.5e-13,
        "BetaQuantileComplement: 'Against the same table, read with the shapes swapped ... the relative error is at most 2.5e-13'",
    ),
}

FUNCS = [
    ("prob.BetaQuantile", "x", "quantile", False),
    ("prob.BetaQuantileXY.y", "one_minus_x", "xy-y", False),
    ("prob.BetaQuantileComplement", "one_minus_x", "complement-swapped", True),
]


def main():
    with open(SRC) as fh:
        rows = json.load(fh)["rows"]
    cases = []
    for r in rows:
        region = "core" if r["core"] else "table"
        for func, ref, tag, swap in FUNCS:
            tol, wording = CLAIMS[(func, r["core"])]
            a, b = r["a"], r["b"]
            if swap:
                a, b = b, a
            cases.append({
                "id": "beta/%s/a=%s,b=%s,p=%s" % (tag, a, b, r["p"]),
                "func": func,
                "args": {"a": float(a), "b": float(b), "p": float(r["p"])},
                "want": float(r[ref]),
                "tol": tol,
                "tol_kind": "rel",
                "claim": "%s %s -> enforced as written, relative %g (%s row of %s)" % (DOC, wording, tol, region, SRC),
            })
    doc = {
        "_comment": "Generated by tools/stressgolden/beta.py from testdata/stress/beta_quantile.json; do not edit by hand. See precision_beta_test.go.",
        "generator": {"source": SRC, "source_digits": 800},
        "cases": cases,
    }
    with open(OUT, "w") as fh:
        json.dump(doc, fh, indent=1)
        fh.write("\n")


main()
