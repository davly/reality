package evt

// Test data for the maximum-likelihood fitters (mle_oracle_test.go).
//
// Every expected value here was computed independently of this package.  The
// maximum-likelihood estimates were found with a multi-start Nelder-Mead / BFGS
// search in scipy (analytic gradients) and then solved to 50 digits with
// mpmath from the score equations; the largest score component at every stored
// point is below 1e-47.  The samples were drawn with scipy.stats.genextreme
// (shape c = -xi) and scipy.stats.genpareto (shape c = xi).

// mleCase is a sample together with its independently computed
// maximum-likelihood estimate and the log-likelihood at that estimate.
type mleCase struct {
	name  string
	data  []float64
	mle   []float64 // GEV: mu, sigma, xi; GPD: sigma, xi
	mleLL float64
	// startOutside is true when the closed-form estimate has zero likelihood on
	// the sample (an observation lies outside its support).
	startOutside bool
}

// mleNoMaximumCase is a sample whose likelihood has no interior maximum: it keeps
// rising toward the shape limit xi = -1, where it is unbounded.
type mleNoMaximumCase struct {
	name string
	data []float64
}

// mleGridRow names one sample of the seeded grid (see mleGridUniforms) and the
// independently computed maximum-likelihood estimate for it.
type mleGridRow struct {
	n     int
	xi    float64
	seed  uint64
	mle   []float64 // GEV: mu, sigma, xi; GPD: sigma, xi
	mleLL float64
}

